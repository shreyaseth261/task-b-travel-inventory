CREATE TABLE transactions (
    id VARCHAR(64) PRIMARY KEY,
    external_id VARCHAR(255) NOT NULL,
    type VARCHAR(32) NOT NULL,
    currency VARCHAR(16) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    total DECIMAL(19, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL
);

CREATE UNIQUE INDEX uk_transactions_external_id ON transactions (external_id);
CREATE INDEX idx_transactions_created_at_id ON transactions (created_at, id);

CREATE TABLE transaction_tax_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(64) NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    rate DECIMAL(19, 6),
    amount DECIMAL(19, 2) NOT NULL,
    position INT NOT NULL
);

CREATE INDEX idx_transaction_tax_lines_txn ON transaction_tax_lines (transaction_id);

CREATE TABLE transaction_fee_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(64) NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    amount DECIMAL(19, 2) NOT NULL,
    position INT NOT NULL
);

CREATE INDEX idx_transaction_fee_lines_txn ON transaction_fee_lines (transaction_id);

CREATE TABLE flight_details (
    transaction_id VARCHAR(64) PRIMARY KEY REFERENCES transactions (id) ON DELETE CASCADE,
    origin VARCHAR(255) NOT NULL,
    destination VARCHAR(255) NOT NULL,
    fare DECIMAL(19, 2) NOT NULL
);

CREATE TABLE flight_coupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(64) NOT NULL REFERENCES flight_details (transaction_id) ON DELETE CASCADE,
    flight_number VARCHAR(64) NOT NULL,
    carrier VARCHAR(64),
    from_code VARCHAR(255) NOT NULL,
    to_code VARCHAR(255) NOT NULL,
    departure TIMESTAMP WITH TIME ZONE NOT NULL,
    arrival TIMESTAMP WITH TIME ZONE NOT NULL,
    position INT NOT NULL
);

CREATE INDEX idx_flight_coupons_txn ON flight_coupons (transaction_id);

CREATE TABLE hotel_details (
    transaction_id VARCHAR(64) PRIMARY KEY REFERENCES transactions (id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    street VARCHAR(255) NOT NULL,
    city VARCHAR(255) NOT NULL,
    country VARCHAR(64) NOT NULL,
    check_in DATE NOT NULL,
    check_out DATE NOT NULL,
    nights INT NOT NULL,
    room_rate_per_night DECIMAL(19, 2) NOT NULL
);

CREATE TABLE hotel_extras (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(64) NOT NULL REFERENCES hotel_details (transaction_id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    amount DECIMAL(19, 2) NOT NULL,
    position INT NOT NULL
);

CREATE TABLE rail_legs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(64) NOT NULL REFERENCES transactions (id) ON DELETE CASCADE,
    origin VARCHAR(255) NOT NULL,
    destination VARCHAR(255) NOT NULL,
    departure TIMESTAMP WITH TIME ZONE NOT NULL,
    arrival TIMESTAMP WITH TIME ZONE NOT NULL,
    train_number VARCHAR(64),
    travel_class VARCHAR(64),
    position INT NOT NULL
);

CREATE INDEX idx_rail_legs_txn ON rail_legs (transaction_id);

CREATE TABLE navan_fee_details (
    transaction_id VARCHAR(64) PRIMARY KEY REFERENCES transactions (id) ON DELETE CASCADE,
    fee_kind VARCHAR(64) NOT NULL,
    description VARCHAR(512),
    related_external_id VARCHAR(255)
);

CREATE TABLE invoices (
    id VARCHAR(64) PRIMARY KEY,
    currency VARCHAR(16) NOT NULL,
    grand_total DECIMAL(19, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    version BIGINT NOT NULL
);

CREATE INDEX idx_invoices_created_at_id ON invoices (created_at, id);

CREATE TABLE invoice_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id VARCHAR(64) NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    transaction_id VARCHAR(64) NOT NULL,
    type VARCHAR(32) NOT NULL,
    external_id VARCHAR(255) NOT NULL,
    currency VARCHAR(16) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    total DECIMAL(19, 2) NOT NULL,
    metadata_snapshot CLOB NOT NULL,
    position INT NOT NULL
);

CREATE INDEX idx_invoice_lines_invoice ON invoice_lines (invoice_id);
CREATE INDEX idx_invoice_lines_transaction_id ON invoice_lines (transaction_id);

CREATE TABLE invoice_line_tax_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_line_id BIGINT NOT NULL REFERENCES invoice_lines (id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    rate DECIMAL(19, 6),
    amount DECIMAL(19, 2) NOT NULL,
    position INT NOT NULL
);

CREATE TABLE invoice_line_fee_lines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_line_id BIGINT NOT NULL REFERENCES invoice_lines (id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    amount DECIMAL(19, 2) NOT NULL,
    position INT NOT NULL
);

CREATE TABLE invoice_tax_rollups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id VARCHAR(64) NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    rate DECIMAL(19, 6),
    amount DECIMAL(19, 2) NOT NULL,
    position INT NOT NULL
);

CREATE TABLE invoice_fee_rollups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id VARCHAR(64) NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    amount DECIMAL(19, 2) NOT NULL,
    position INT NOT NULL
);
